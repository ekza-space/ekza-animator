// M6A-INT-13 (M6A-SPEC §5.27, the B0a notes' option C): the Model operators chunk and its eager side. The manifest is
// generated from the chunk's definitions (`EKZA_WRITE_MODEL_MANIFEST=1 pnpm --filter @ekza-animator/editor-core exec
// vitest run test/m6a/model-ops.test.ts` rewrites it) and must not drift; the proxies the registry holds are the
// chunk's operators once it has loaded; no eager editor-core module imports a value from the chunk's modules.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { describe, expect, it } from 'vitest';
import { BUILTIN_OPERATORS } from '../../src/operators/builtin';
import { MODEL_OPERATOR_MANIFEST } from '../../src/operators/builtin/modelManifest';
import '../../src/testing';
import {
  MODEL_OPERATOR_PROXIES,
  modelOperatorExtras,
  modelOperators,
  operatorMeta,
} from '../../src/operators/builtin/modelOps';
import { MODEL_OPERATOR_GROUPS, MODEL_OPERATORS } from '../../src/operators/builtin/modelOpsChunk';

const SRC = resolve(dirname(fileURLToPath(import.meta.url)), '../../src');
const MANIFEST_FILE = join(SRC, 'operators/builtin/modelManifest.ts');

function manifestSource(): string {
  const groups = Object.fromEntries(
    Object.entries(MODEL_OPERATOR_GROUPS).map(([group, defs]) => [group, defs.map(operatorMeta)]),
  );
  return [
    '// GENERATED by test/m6a/model-ops.test.ts (EKZA_WRITE_MODEL_MANIFEST=1); the test fails when it drifts. The eager',
    "// metadata of the Model operators chunk's operators (M6A-INT-13): see ./modelOps.",
    "import type { ModelOperatorManifest } from './modelOps';",
    '',
    `export const MODEL_OPERATOR_MANIFEST: ModelOperatorManifest = ${JSON.stringify(groups)};`,
    '',
  ].join('\n');
}

describe('the Model operators chunk (M6A-INT-13)', () => {
  it('the manifest is the metadata of the chunk’s definitions, group by group', () => {
    if (process.env['EKZA_WRITE_MODEL_MANIFEST'] === '1') writeFileSync(MANIFEST_FILE, manifestSource());
    for (const [group, defs] of Object.entries(MODEL_OPERATOR_GROUPS)) {
      expect([group, MODEL_OPERATOR_MANIFEST[group as keyof typeof MODEL_OPERATOR_MANIFEST]]).toEqual([
        group,
        defs.map(operatorMeta),
      ]);
    }
  });

  it.skipIf(process.env['EKZA_WRITE_MODEL_MANIFEST'] === '1')(
    'the registry’s proxies are the chunk’s operators once it has loaded (the test setup installs it)',
    () => {
      expect(modelOperators()).not.toBeNull();
      expect(modelOperatorExtras()).toEqual([]);
      const proxies = [
        ...MODEL_OPERATOR_PROXIES.mesh,
        ...MODEL_OPERATOR_PROXIES.select,
        ...MODEL_OPERATOR_PROXIES.content,
      ];
      expect(proxies.map((def) => def.id)).toEqual(MODEL_OPERATORS.map((def) => def.id));
      for (const [index, proxy] of proxies.entries()) {
        const def = MODEL_OPERATORS[index];
        expect(Object.keys(proxy).sort()).toEqual(Object.keys(def ?? {}).sort());
        for (const key of Object.keys(proxy)) {
          expect([proxy.id, key, (proxy as never)[key]]).toEqual([proxy.id, key, (def as never)[key]]);
        }
      }
      for (const proxy of proxies) expect(BUILTIN_OPERATORS).toContain(proxy);
    },
  );

  it('no eager editor-core module imports a value from the chunk (the bundler keeps a module once one does)', () => {
    const chunk = new Set<string>(['operators/builtin/modelOpsChunk', 'operators/builtin/modelMenus']);
    const offenders: string[] = [];
    for (const file of sources(SRC)) {
      const rel = relative(SRC, file).replace(/\.ts$/, '');
      // The chunk itself, the barrel (re-exports nobody eager uses are dropped) and the test kit (never in the app).
      if (rel === 'operators/builtin/modelOpsChunk' || rel === 'index' || rel.startsWith('testing/')) continue;
      for (const spec of valueImports(readFileSync(file, 'utf8'))) {
        if (!spec.startsWith('.')) continue;
        const target = relative(SRC, resolve(dirname(file), spec)).replace(/\.ts$/, '');
        if (chunk.has(target)) offenders.push(`${rel} → ${spec}`);
      }
    }
    expect(offenders).toEqual([]);
  });
});

function sources(dir: string): string[] {
  return readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) return sources(path);
    return entry.name.endsWith('.ts') ? [path] : [];
  });
}

/** Specifiers of the static imports and re-exports of `code` that bring in values (type-only ones excluded). */
function valueImports(code: string): string[] {
  const out: string[] = [];
  const statement = /(?:^|\n)\s*(import|export)\s+(type\s+)?([^;]*?)\s+from\s+'([^']+)'/g;
  for (const match of code.matchAll(statement)) {
    const [, , typeOnly, clause = '', from = ''] = match;
    if (typeOnly !== undefined) continue;
    const named = /^\{([\s\S]*)\}$/.exec(clause.trim());
    if (named !== null) {
      const specifiers = (named[1] ?? '')
        .split(',')
        .map((s) => s.trim())
        .filter((s) => s.length > 0);
      if (specifiers.every((s) => s.startsWith('type '))) continue;
    }
    out.push(from);
  }
  return out;
}
