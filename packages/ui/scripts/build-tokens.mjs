#!/usr/bin/env node
// Generates the CSS of @ekza-animator/ui that is derived from other sources (research 09 §8; MVP-SPEC §7 WP-8):
//
//   css/tokens.css          CSS custom properties from tokens.json (the source of truth)
//   css/dockview-core.css   the structural part of dockview-react 8.4.0's stylesheet without its colour themes
//                           (the shell's theme is css/dockview-theme.css, built on the tokens)
//
// The editor package cannot import dockview's stylesheet itself (it is `"sideEffects": false`, so bundlers drop
// bare CSS imports), and neither `ui` nor `apps/web` depends on dockview-react, so the core rules are vendored here
// with their licence header. The output is byte-for-byte deterministic.
//
// Usage: node packages/ui/scripts/build-tokens.mjs [--check]
//   --check  write nothing; exit 1 when a generated file on disk differs from what this script generates

import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const UI_DIR = resolve(dirname(fileURLToPath(import.meta.url)), '..');
export const TOKENS_JSON = join(UI_DIR, 'tokens.json');
export const TOKENS_CSS = join(UI_DIR, 'css', 'tokens.css');
export const DOCKVIEW_CORE_CSS = join(UI_DIR, 'css', 'dockview-core.css');
export const DOCKVIEW_VERSION = '8.4.0';

const HEADER = '/* Generated by packages/ui/scripts/build-tokens.mjs from packages/ui/tokens.json. Do not edit. */';
/** Token groups written as plain custom properties, in this order. */
const PLAIN_GROUPS = ['color', 'radius', 'space', 'size', 'font', 'shadow', 'motion', 'z'];

/** CSS custom properties for every token group; `type` styles become `--type-<name>-{size,line,weight}`. */
export function renderTokensCss(tokens) {
  const lines = [HEADER, ':root {'];
  for (const group of PLAIN_GROUPS) {
    const entries = Object.entries(tokens[group] ?? {});
    if (entries.length === 0) continue;
    lines.push(`  /* ${group} */`);
    for (const [name, value] of entries) lines.push(`  --${name}: ${value};`);
  }
  const types = Object.entries(tokens.type ?? {});
  if (types.length > 0) {
    lines.push('  /* type */');
    for (const [name, style] of types) {
      lines.push(`  --type-${name}-size: ${style.size};`);
      lines.push(`  --type-${name}-line: ${style.line};`);
      lines.push(`  --type-${name}-weight: ${style.weight};`);
    }
  }
  lines.push('}');
  const motion = Object.keys(tokens.motion ?? {});
  if (motion.length > 0) {
    lines.push('', '@media (prefers-reduced-motion: reduce) {', '  :root {');
    for (const name of motion) lines.push(`    --${name}: 0ms;`);
    lines.push('  }', '}');
  }
  return `${lines.join('\n')}\n`;
}

/**
 * Removes every rule whose selector names a `.dockview-theme-*` class (and at-rules left empty by that), keeping
 * the structural rules. A small brace-depth parser is enough: dockview's stylesheet has no braces inside strings.
 */
export function stripDockviewThemes(css) {
  const out = [];
  for (const block of topLevelBlocks(css)) {
    const kept = keepBlock(block);
    if (kept !== null) out.push(kept);
  }
  return out.join('\n');
}

export function renderDockviewCoreCss(source) {
  const header = [
    `/* Structural rules of dockview-react ${DOCKVIEW_VERSION} dist/styles/dockview.css, colour themes removed.`,
    '   Generated by packages/ui/scripts/build-tokens.mjs. Do not edit.',
    '   SPDX-FileCopyrightText: 2021 mathuo (https://github.com/dockview/dockview)',
    '   SPDX-License-Identifier: MIT */',
  ].join('\n');
  return `${header}\n${stripDockviewThemes(source)}\n`;
}

/** Splits a stylesheet into top-level statements: `{ prelude, body }` for blocks, `{ text }` for comments etc. */
function topLevelBlocks(css) {
  const blocks = [];
  let i = 0;
  let start = 0;
  while (i < css.length) {
    if (css.startsWith('/*', i)) {
      const end = css.indexOf('*/', i + 2);
      i = end === -1 ? css.length : end + 2;
      if (css.slice(start, i).trim().startsWith('/*')) {
        blocks.push({ text: css.slice(start, i).trim() });
        start = i;
      }
      continue;
    }
    const ch = css[i];
    if (ch === ';' && css.slice(start, i).trim().startsWith('@')) {
      blocks.push({ text: `${css.slice(start, i + 1).trim()}` });
      i += 1;
      start = i;
      continue;
    }
    if (ch === '{') {
      const close = matchingBrace(css, i);
      blocks.push({ prelude: css.slice(start, i).trim(), body: css.slice(i + 1, close) });
      i = close + 1;
      start = i;
      continue;
    }
    i += 1;
  }
  return blocks;
}

function matchingBrace(css, open) {
  let depth = 0;
  for (let i = open; i < css.length; i++) {
    if (css.startsWith('/*', i)) {
      const end = css.indexOf('*/', i + 2);
      i = end === -1 ? css.length : end + 1;
      continue;
    }
    if (css[i] === '{') depth += 1;
    else if (css[i] === '}') {
      depth -= 1;
      if (depth === 0) return i;
    }
  }
  throw new Error(`unbalanced braces at offset ${open}`);
}

function keepBlock(block) {
  if (block.prelude === undefined) return block.text.startsWith('/*') ? null : block.text;
  if (block.prelude.startsWith('@')) {
    if (!/^@(media|supports|layer|container)\b/.test(block.prelude)) return `${block.prelude} {${block.body}}`;
    const inner = topLevelBlocks(block.body)
      .map(keepBlock)
      .filter((rule) => rule !== null);
    if (inner.length === 0) return null;
    return `${block.prelude} {\n${inner.map((rule) => indent(rule)).join('\n')}\n}`;
  }
  if (block.prelude.includes('.dockview-theme-')) return null;
  return `${block.prelude} {${block.body}}`;
}

function indent(text) {
  return text
    .split('\n')
    .map((line) => (line.length === 0 ? line : `  ${line}`))
    .join('\n');
}

/** dockview-react's stylesheet, resolved the way the editor package resolves the library. */
export function dockviewSourcePath() {
  const require = createRequire(join(UI_DIR, '..', 'editor', 'package.json'));
  return require.resolve('dockview-react/dist/styles/dockview.css');
}

/** Formats CSS with the repository's Biome configuration, so `pnpm format:check` accepts the generated files. */
export function formatWithBiome(path, css) {
  const biome = join(UI_DIR, '..', '..', 'node_modules', '.bin', process.platform === 'win32' ? 'biome.cmd' : 'biome');
  return execFileSync(biome, ['format', `--stdin-file-path=${path}`], {
    input: css,
    encoding: 'utf8',
    cwd: join(UI_DIR, '..', '..'),
    maxBuffer: 16 * 1024 * 1024,
  });
}

export function generate() {
  const tokens = JSON.parse(readFileSync(TOKENS_JSON, 'utf8'));
  const dockview = renderDockviewCoreCss(readFileSync(dockviewSourcePath(), 'utf8'));
  return new Map([
    [TOKENS_CSS, formatWithBiome(TOKENS_CSS, renderTokensCss(tokens))],
    [DOCKVIEW_CORE_CSS, formatWithBiome(DOCKVIEW_CORE_CSS, dockview)],
  ]);
}

function main(argv) {
  const check = argv.includes('--check');
  let stale = 0;
  for (const [path, content] of generate()) {
    let current = null;
    try {
      current = readFileSync(path, 'utf8');
    } catch {
      current = null;
    }
    if (current === content) continue;
    if (check) {
      console.error(`stale: ${path}`);
      stale += 1;
    } else {
      writeFileSync(path, content);
      process.stdout.write(`wrote ${path}\n`);
    }
  }
  if (stale > 0) {
    console.error('Run `node packages/ui/scripts/build-tokens.mjs` and commit the result.');
    process.exitCode = 1;
  }
}

if (process.argv[1] !== undefined && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main(process.argv.slice(2));
}
