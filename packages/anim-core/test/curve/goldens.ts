import { readFileSync } from 'node:fs';
import type { AnimCurve, InfinityMode, KeyData, TangentType } from '../../src';

/** One key in the goldens' compact form: [t, v, inType, outType, inDt, inDv, outDt, outDv]. */
type GoldenKey = [number, number, TangentType, TangentType, number, number, number, number];

export interface GoldenCurve {
  readonly name: string;
  readonly weighted: boolean;
  readonly pre: InfinityMode;
  readonly post: InfinityMode;
  readonly keys: readonly GoldenKey[];
  /** [key index, side, AnimX slope] for every auto/autoMix/autoEase side. */
  readonly autoSlopes: readonly [number, 'in' | 'out', number][];
  /** [frame, AnimX value]. */
  readonly samples: readonly [number, number][];
}

export interface Goldens {
  readonly source: string;
  readonly commit: string;
  readonly seed: number;
  readonly curves: readonly GoldenCurve[];
}

/** AnimX goldens generated by tooling/animx-oracle (committed; see its README). */
export function readAnimxGoldens(): Goldens {
  const raw: unknown = JSON.parse(readFileSync(new URL('../goldens/animx-goldens.json', import.meta.url), 'utf8'));
  return raw as Goldens;
}

export function goldenCurve(g: GoldenCurve): AnimCurve {
  const keys: KeyData[] = g.keys.map(([t, v, inType, outType, inDt, inDv, outDt, outDv]) => ({
    t,
    v,
    inType,
    outType,
    inHandle: { dt: inDt, dv: inDv },
    outHandle: { dt: outDt, dv: outDv },
    broken: true,
    weightLocked: false,
  }));
  return { keys, weighted: g.weighted, pre: g.pre, post: g.post };
}
