// Fixture helpers of the shared test kit (MVP-SPEC §3 conventions 7 and 13, §7 WP-0b). Node only.
import { existsSync, readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { EkzaError } from '@ekza-studio/anim-core';

export type LicensedFixture = 'seed-san.vrm' | 'polybot.vrm' | 'quaternius-ual.glb' | 'quaternius-idle-meshopt.glb';
export type SyntheticFixture = 'humanoid-skeleton.json' | 'wave-doc.json' | 'rest-pose.json';

/** Licensed binaries live in fixtures/models (avatars) and fixtures/animations (clip libraries). */
const LICENSED_DIR: Readonly<Record<LicensedFixture, 'models' | 'animations'>> = {
  'seed-san.vrm': 'models',
  'polybot.vrm': 'models',
  'quaternius-ual.glb': 'animations',
  'quaternius-idle-meshopt.glb': 'animations',
};

/** `<repo>/fixtures/`, resolved from this file (packages/doc/src/testing/). */
const FIXTURES_ROOT = new URL('../../../../fixtures/', import.meta.url);

/** Absolute path of a licensed fixture (fixtures/LICENSES.md). The file may not exist yet (WP-4 adds one). */
export function fixturePath(name: LicensedFixture): string {
  const dir = LICENSED_DIR[name];
  if (dir === undefined) throw new EkzaError('asset-missing', `Unknown licensed fixture '${String(name)}'`);
  return fileURLToPath(new URL(`${dir}/${name}`, FIXTURES_ROOT));
}

/** The exact bytes of a licensed fixture; throws EkzaError('asset-missing') when the file is absent. */
export function readFixture(name: LicensedFixture): Uint8Array {
  return readBytes(fixturePath(name), name);
}

/**
 * A synthetic fixture parsed from fixtures/synthetic/ (generated by tooling/make-synthetic-fixtures.mjs). The caller
 * narrows the result: `humanoid-skeleton.json` is a `SkeletonDesc`, `wave-doc.json` a `DocSnapshot`.
 */
export function readSyntheticFixture(name: SyntheticFixture): unknown {
  const path = fileURLToPath(new URL(`synthetic/${name}`, FIXTURES_ROOT));
  const text = new TextDecoder().decode(readBytes(path, name));
  return JSON.parse(text) as unknown;
}

function readBytes(path: string, name: string): Uint8Array {
  if (!existsSync(path)) throw new EkzaError('asset-missing', `Fixture '${name}' not found at ${path}`, { path });
  // Copy out of Node's Buffer so callers get a plain Uint8Array that owns its memory.
  return new Uint8Array(readFileSync(path));
}
